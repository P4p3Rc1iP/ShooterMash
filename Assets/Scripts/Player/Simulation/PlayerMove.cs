using System.Collections.Generic;
using UnityEngine;

namespace ShooterMashup.Player
{
    /// <summary>
    /// Player movement simulation, modelled on Wolfenstein: Enemy Territory's Pmove.
    ///
    /// It is a pure function of (PlayerState, PlayerCmd, world collision, MoveConfig): the same
    /// inputs always give the same output, so it can run identically on a server and as client
    /// prediction. Features live in separate partial files (Walk, Air, Water, Ladder, Prone,
    /// Lean, Sprint, Ground, SlideMove), each with an enable flag in MoveConfig.
    /// </summary>
    public sealed partial class PlayerMove
    {
        const float Overclip = 1.001f;
        // ET's small internal tolerances are written as multiples of this, so they stay
        // recognisable against the original source. Everything tunable is in MoveConfig.
        const float Inch = 0.0254f;
        // ET stores angles as 16-bit shorts and clamps pitch at +-16000 of them.
        public const float PitchLimit = 16000f * 360f / 65536f;

        readonly MoveConfig cfg;
        IPmoveWorld world;

        /// <summary>Events generated by the last Move call. Cleared at the start of each Move.</summary>
        public readonly List<PmEvent> Events = new List<PmEvent>();

        // State being simulated and the command driving it.
        PlayerState ps;
        PlayerCmd cmd;
        Vector3 mins, maxs;

        // Per-step locals (ET's "pml"). Reset at the start of every step.
        Vector3 forward, right, up;
        float frametime;
        int msec;
        bool walking;
        bool groundPlane;
        TraceResult groundTrace;
        float impactSpeed;
        Vector3 previousOrigin;
        Vector3 previousVelocity;
        int previousWaterLevel;
        bool ladder;
        bool ladderForward;
        Vector3 ladderNormal;

        public PlayerMove(MoveConfig config, IPmoveWorld world)
        {
            cfg = config;
            this.world = world;
        }

        public MoveConfig Config => cfg;

        public IPmoveWorld World
        {
            get => world;
            set => world = value;
        }

        /// <summary>
        /// Advance <paramref name="state"/> to <c>command.serverTime</c>. Long gaps are split into
        /// steps of at most MoveConfig.maxStepMsec.
        /// </summary>
        public void Move(ref PlayerState state, PlayerCmd command)
        {
            Events.Clear();

            int finalTime = command.serverTime;
            if (finalTime < state.commandTime)
                return; // should not happen
            if (finalTime > state.commandTime + 1000)
                state.commandTime = finalTime - 1000;

            ps = state;
            cmd = command;

            while (ps.commandTime != finalTime)
            {
                int ms = finalTime - ps.commandTime;
                if (ms > cfg.maxStepMsec)
                    ms = cfg.maxStepMsec;
                cmd.serverTime = ps.commandTime + ms;

                MoveSingle();

                if ((ps.pmFlags & PmFlags.JumpHeld) != 0)
                    cmd.upMove = 20;
            }

            state = ps;
        }

        void MoveSingle()
        {
            walking = false;
            groundPlane = false;
            groundTrace = default;
            impactSpeed = 0f;
            ladder = false;
            ladderForward = false;
            ps.waterLevel = 0;
            ps.waterType = Contents.None;

            // Running (not walking) speeds always make footstep noise.
            if (Mathf.Abs(cmd.forwardMove) > 64 || Mathf.Abs(cmd.rightMove) > 64)
                cmd.buttons &= ~CmdButtons.Walk;

            msec = Mathf.Clamp(cmd.serverTime - ps.commandTime, 1, 200);
            ps.commandTime = cmd.serverTime;
            previousOrigin = ps.origin;
            previousVelocity = ps.velocity;
            frametime = msec * 0.001f;

            if (ps.pmType != PmType.Freeze)
                UpdateViewAngles();

            AngleVectors(ps.viewAngles, out forward, out right, out up);

            if (cmd.upMove < 10)
                ps.pmFlags &= ~PmFlags.JumpHeld;

            if (cmd.forwardMove < 0)
                ps.pmFlags |= PmFlags.BackwardsRun;
            else if (cmd.forwardMove > 0 || cmd.rightMove != 0)
                ps.pmFlags &= ~PmFlags.BackwardsRun;

            if (ps.pmType == PmType.Dead || ps.pmType == PmType.Freeze)
            {
                cmd.forwardMove = 0;
                cmd.rightMove = 0;
                cmd.upMove = 0;
            }

            if (ps.pmType == PmType.Noclip)
            {
                NoclipMove();
                DropTimers();
                return;
            }

            if (ps.pmType == PmType.Freeze)
                return;

            SetWaterLevel();
            previousWaterLevel = ps.waterLevel;

            // Sets mins, maxs and viewHeight.
            if (!CheckProne())
                CheckDuck();

            GroundTrace();

            if (ps.pmType == PmType.Dead)
                DeadMove();

            CheckLadderMove();
            DropTimers();

            if (ladder)
                LadderMove();
            else if ((ps.pmFlags & PmFlags.TimeWaterJump) != 0)
                WaterJumpMove();
            else if (ps.waterLevel > 1)
                WaterMove();
            else if (walking)
                WalkMove();
            else
                AirMove();

            Sprint();

            GroundTrace();
            SetWaterLevel();

            Footsteps();
            WaterEvents();

            // ET rounds velocity to whole qu/s here to save network bandwidth, which also makes
            // jump height depend on framerate (the "125 fps jump"). We deliberately don't.
        }

        // ------------------------------------------------------------------ view angles

        void UpdateViewAngles()
        {
            if (ps.pmType == PmType.Dead)
                return;

            Vector2 old = ps.viewAngles;

            float pitch = cmd.pitch + ps.deltaAngles.x;
            if (pitch > PitchLimit)
            {
                ps.deltaAngles.x = PitchLimit - cmd.pitch;
                pitch = PitchLimit;
            }
            else if (pitch < -PitchLimit)
            {
                ps.deltaAngles.x = -PitchLimit - cmd.pitch;
                pitch = -PitchLimit;
            }
            ps.viewAngles.x = pitch;
            ps.viewAngles.y = Mathf.Repeat(cmd.yaw + ps.deltaAngles.y, 360f);

            if (ps.IsProne)
                ClampProneView(old);

            UpdateLean();
        }

        // ------------------------------------------------------------------ shared helpers

        float BaseSpeed => cfg.speed * ps.modifiers.speed;

        /// <summary>
        /// Scale that turns the -127..127 cmd axes into m/s, without the sqrt(2) diagonal boost.
        /// Note that, as in ET, holding jump or crouch is part of the vector and lowers this.
        /// </summary>
        float CmdScale()
        {
            int max = Mathf.Abs(cmd.forwardMove);
            if (Mathf.Abs(cmd.rightMove) > max) max = Mathf.Abs(cmd.rightMove);
            if (Mathf.Abs(cmd.upMove) > max) max = Mathf.Abs(cmd.upMove);
            if (max == 0)
                return 0f;

            float total = Mathf.Sqrt(cmd.forwardMove * cmd.forwardMove
                                     + cmd.rightMove * cmd.rightMove
                                     + cmd.upMove * cmd.upMove);
            float scale = BaseSpeed * max / (127f * total);

            if (cfg.enableSprint && cmd.Has(CmdButtons.Sprint) && ps.stamina > cfg.minStaminaToSprint)
                scale *= cfg.sprintSpeedScale;
            else
                scale *= cfg.runSpeedScale;

            if (ps.pmType == PmType.Noclip)
                scale *= 3f;

            return scale;
        }

        /// <summary>Quake 2 style acceleration. This is what makes strafe jumping possible.</summary>
        void Accelerate(Vector3 wishdir, float wishspeed, float accel)
        {
            float currentspeed = Vector3.Dot(ps.velocity, wishdir);
            float addspeed = wishspeed - currentspeed;
            if (addspeed <= 0f)
                return;
            float accelspeed = accel * frametime * wishspeed;
            if (accelspeed > addspeed)
                accelspeed = addspeed;
            ps.velocity += accelspeed * wishdir;
        }

        /// <summary>Ground, water and ladder friction.</summary>
        void Friction()
        {
            Vector3 vel = ps.velocity;
            Vector3 vec = vel;
            if (walking)
                vec.y = 0f; // ignore slope movement

            float speed = vec.magnitude;
            if (speed < 1f * Inch && ps.pmType != PmType.Noclip)
            {
                ps.velocity.x = 0f;
                ps.velocity.z = 0f; // allow sinking underwater
                return;
            }

            float drop = 0f;

            if (ps.waterLevel <= 1 && walking
                && (groundTrace.surfaceFlags & SurfaceFlags.Slick) == 0
                && (ps.pmFlags & PmFlags.TimeKnockback) == 0)
            {
                float control = speed < cfg.stopSpeed ? cfg.stopSpeed : speed;
                drop += control * cfg.friction * frametime;
            }

            if (ps.waterLevel > 0)
            {
                float f = (ps.waterType & Contents.Slime) != 0 ? cfg.slimeFriction : cfg.waterFriction;
                drop += speed * f * ps.waterLevel * frametime;
            }

            if (ladder)
                drop += speed * cfg.ladderFriction * frametime;

            float newspeed = speed - drop;
            if (newspeed < 0f)
                newspeed = 0f;
            newspeed /= speed;

            if (ps.pmType == PmType.Noclip && drop < 1f * Inch && speed < 3f * Inch)
                newspeed = 0f;

            ps.velocity = vel * newspeed;
        }

        void DropTimers()
        {
            if (ps.pmTime == 0)
                return;
            if (msec >= ps.pmTime)
            {
                ps.pmFlags &= ~PmFlags.AllTimes;
                ps.pmTime = 0;
            }
            else
            {
                ps.pmTime -= msec;
            }
        }

        /// <summary>Which way the legs face relative to the view, for animation.</summary>
        void SetMovementDir()
        {
            Vector3 moved = ps.origin - previousOrigin;
            float speed = moved.magnitude;

            if ((cmd.forwardMove != 0 || cmd.rightMove != 0) && ps.onGround && speed > frametime * 5f * Inch)
            {
                float moveYaw = Mathf.Atan2(moved.x, moved.z) * Mathf.Rad2Deg;
                int dir = (int)Mathf.DeltaAngle(ps.viewAngles.y, moveYaw);
                if (cmd.forwardMove < 0)
                    dir = (int)Mathf.DeltaAngle(0f, dir + 180f);
                ps.movementDir = (sbyte)Mathf.Clamp(dir, -75, 75);
            }
            else
            {
                ps.movementDir = 0;
            }
        }

        void AddEvent(PmEventType type, int param = 0, SurfaceType surface = SurfaceType.Default)
        {
            Events.Add(new PmEvent { type = type, param = param, surface = surface });
        }

        public static void AngleVectors(Vector2 angles, out Vector3 forward, out Vector3 right, out Vector3 up)
        {
            Quaternion q = Quaternion.Euler(angles.x, angles.y, 0f);
            forward = q * Vector3.forward;
            right = q * Vector3.right;
            up = q * Vector3.up;
        }

        /// <summary>Remove the component of <paramref name="v"/> going into the plane, plus a tiny bit extra.</summary>
        static Vector3 ClipVelocity(Vector3 v, Vector3 normal, float overbounce = Overclip)
        {
            float backoff = Vector3.Dot(v, normal);
            if (backoff < 0f)
                backoff *= overbounce;
            else
                backoff /= overbounce;
            return v - normal * backoff;
        }

        /// <summary>Normalise in place, returning the original length (0 stays 0, like Quake's VectorNormalize).</summary>
        static float Normalize(ref Vector3 v)
        {
            float len = v.magnitude;
            if (len > 0f)
                v /= len;
            return len;
        }
    }
}
